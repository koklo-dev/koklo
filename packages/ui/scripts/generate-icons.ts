const HEADER = "// @generated by scripts/generate-icons.ts - DO NOT EDIT\n";
const PATH_RE = /<path d="([^"]+)"/;

function readPath(svgDir: string, file: string): string {
  const d = PATH_RE.exec(readFileSync(join(svgDir, file), "utf8"))?.[1];
  if (!d) throw new Error(`Aucun tracé dans ${file}`);
  return d;
}

export function generate(outDir: string, svgDir: string): void {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const name of ICON_NAMES) {
    const outline = readPath(svgDir, `${name}.svg`);
    const filled = readPath(svgDir, `${name}-fill.svg`);
    const body = `${HEADER}export const outline = ${JSON.stringify(outline)};\nexport const filled = ${JSON.stringify(filled)};\n`;
    writeFileSync(join(outDir, `${name}.ts`), body);
  }
  const loaders = ICON_NAMES.map((n) => `  ${n}: () => import("./${n}.ts"),`).join("\n");
  writeFileSync(
    join(outDir, "registry.ts"),
    `${HEADER}export const iconLoaders = {\n${loaders}\n} as const;\n\nexport type IconName = keyof typeof iconLoaders;\n`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const svgDir = join(
    dirname(createRequire(import.meta.url).resolve("@material-symbols/svg-400/package.json")),
    "rounded",
  );
  generate(join(root, "src/icons/generated"), svgDir);
}
